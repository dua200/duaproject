function wStep(step, answer) {
    answers['step' + (step - 1)] = answer;
    document.getElementById('wizard-step-' + (step - 1)).style.display = 'none';
    if (step <= 3) document.getElementById('wizard-step-' + step).style.display = 'block';
}

