// ─── Verander taal ───
function setLang(l) {
    lang = l;
    document.getElementById('langLabel').textContent = l.toUpperCase();
    document.getElementById('langMenu').classList.remove('open');
    ['nl','en','pl','ro','tr','ar'].forEach(x => {
        const btn = document.getElementById('btn-' + x);
        if (btn) btn.classList.toggle('active', x === l);
    });
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (T[l] && T[l][key]) el.textContent = T[l][key];
    });
    // Placeholders updaten
    const sp = document.getElementById('searchInput');
    if (sp && T[l].search_placeholder) sp.placeholder = T[l].search_placeholder;
    document.documentElement.lang = l;
    // RTL voor Arabisch
    document.documentElement.dir = (l === 'ar') ? 'rtl' : 'ltr';
}

// ─── Taal dropdown ───
document.getElementById('langToggle').addEventListener('click', e => {
    e.stopPropagation();
    document.getElementById('langMenu').classList.toggle('open');
});
document.addEventListener('click', () => {
    document.getElementById('langMenu').classList.remove('open');
});

// ─── Zoekfunctie ───
function doSearch() {
    const query = document.getElementById('searchInput').value.toLowerCase().trim();
    const resultBox = document.getElementById('searchResult');
    if (!query) { resultBox.style.display = 'none'; return; }

    let found = null;
    for (const item of SEARCH_INDEX) {
        if (item.keywords.some(k => query.includes(k) || k.includes(query))) {
            found = item;
            break;
        }
    }

    if (found) {
        resultBox.style.display = 'block';
        const action = found.page === 'page-digid'
            ? `window.location.href='html/digi.html'`
            : `openPage('${found.page}')`;
        resultBox.innerHTML = `<span>✅ Gevonden:</span> <button onclick="${action}" style="background:var(--blue);color:#fff;border:none;padding:8px 16px;border-radius:4px;font-family:inherit;font-weight:800;cursor:pointer;margin-left:10px;">${T[lang][found.cat] || found.cat}</button>`;
    } else {
        resultBox.style.display = 'block';
        resultBox.innerHTML = `<span>❌ ${T[lang].search_no_result || 'Niets gevonden.'}</span>`;
    }
}

document.addEventListener('DOMContentLoaded', () => {
    const input = document.getElementById('searchInput');
    if (input) {
        input.addEventListener('keydown', e => { if (e.key === 'Enter') doSearch(); });
    }
});

