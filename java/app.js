// ─── Huidige taal ───
let lang = localStorage.getItem('mw_lang') || 'nl';

// ─── Verander taal ───
function setLang(l) {
    lang = l;
    localStorage.setItem('mw_lang', l);
    document.getElementById('langLabel').textContent = l.toUpperCase();
    document.getElementById('langMenu').classList.remove('open');
    ['nl','en','pl','ro','tr','ar'].forEach(x => {
        const btn = document.getElementById('btn-' + x);
        if (btn) btn.classList.toggle('active', x === l);
    });
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (T[l] && T[l][key]) el.textContent = T[l][key];
    });
    // Placeholders updaten
    const sp = document.getElementById('searchInput');
    if (sp && T[l].search_placeholder) sp.placeholder = T[l].search_placeholder;
    document.documentElement.lang = l;
    // Update overlay taal labels
    document.querySelectorAll('.overlay-lang-label').forEach(el => el.textContent = l.toUpperCase());
    // RTL voor Arabisch
    document.documentElement.dir = (l === 'ar') ? 'rtl' : 'ltr';
}

// ─── Taal dropdown ───
document.getElementById('langToggle').addEventListener('click', e => {
    e.stopPropagation();
    document.getElementById('langMenu').classList.toggle('open');
});
document.addEventListener('click', () => {
    document.getElementById('langMenu').classList.remove('open');
});

// ─── Zoekfunctie ───
function doSearch() {
    const query = document.getElementById('searchInput').value.toLowerCase().trim();
    const resultBox = document.getElementById('searchResult');
    if (!query) { resultBox.style.display = 'none'; return; }

    let found = null;
    for (const item of SEARCH_INDEX) {
        if (item.keywords.some(k => query.includes(k) || k.includes(query))) {
            found = item;
            break;
        }
    }

    if (found) {
        resultBox.style.display = 'block';
        const action = found.page === 'page-digid'
            ? `window.location.href='html/digi.html'`
            : `openPage('${found.page}')`;
        resultBox.innerHTML = `<span>✅ Gevonden:</span> <button onclick="${action}" style="background:var(--blue);color:#fff;border:none;padding:8px 16px;border-radius:4px;font-family:inherit;font-weight:800;cursor:pointer;margin-left:10px;">${T[lang][found.cat] || found.cat}</button>`;
    } else {
        resultBox.style.display = 'block';
        resultBox.innerHTML = `<span>❌ ${T[lang].search_no_result || 'Niets gevonden.'}</span>`;
    }
}

document.addEventListener('DOMContentLoaded', () => {
    const input = document.getElementById('searchInput');
    if (input) {
        input.addEventListener('keydown', e => { if (e.key === 'Enter') doSearch(); });
    }
    // Herstel opgeslagen taal
    const saved = localStorage.getItem('mw_lang');
    if (saved && saved !== 'nl') setLang(saved);
});

// ─── Pagina openen / sluiten ───
function openPage(id) {
    document.getElementById(id).classList.add('open');
    window.scrollTo(0, 0);
    // Update taal label in overlay naar huidige taal
    document.querySelectorAll('.overlay-lang-label').forEach(el => el.textContent = lang.toUpperCase());
}
function closePage(id) {
    document.getElementById(id).classList.remove('open');
}

// ─── Wizard ───
let answers = {};

function wStep(step, answer) {
    answers['step' + (step - 1)] = answer;
    document.getElementById('wizard-step-' + (step - 1)).style.display = 'none';
    if (step <= 3) document.getElementById('wizard-step-' + step).style.display = 'block';
}

function wResult(answer) {
    answers['step3'] = answer;
    document.getElementById('wizard-step-3').style.display = 'none';
    const res = document.getElementById('wizard-result');
    const txt = document.getElementById('wizard-result-text');
    res.classList.add('show');
    const t = T[lang];
    if (answers.step1 === 'salary' && answer === 'afraid') txt.textContent = t.res_salary_afraid;
    else if (answers.step2 === 'housing' && answer === 'afraid') txt.textContent = t.res_housing_afraid;
    else txt.textContent = t.res_general;
}

function wRestart() {
    answers = {};
    document.getElementById('wizard-result').classList.remove('show');
    document.getElementById('wizard-step-2').style.display = 'none';
    document.getElementById('wizard-step-3').style.display = 'none';
    document.getElementById('wizard-step-1').style.display = 'block';
}